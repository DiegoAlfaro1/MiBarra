-- MiBarra initial schema.
-- Money is stored as integer cents. Every table has row level security enabled;
-- orders and loyalty points can only be written through security-definer functions.

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text check (char_length(display_name) <= 80),
  created_at timestamptz not null default now()
);

create table public.shops (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 1 and 120),
  currency char(3) not null check (currency ~ '^[A-Z]{3}$'),
  created_at timestamptz not null default now()
);

create table public.shop_staff (
  shop_id uuid not null references public.shops (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  role text not null check (role in ('owner', 'barista')),
  created_at timestamptz not null default now(),
  primary key (shop_id, user_id)
);
create index shop_staff_user_id_idx on public.shop_staff (user_id);

create table public.products (
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references public.shops (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 120),
  price_cents integer not null check (price_cents >= 0),
  is_available boolean not null default true,
  created_at timestamptz not null default now()
);
create index products_shop_id_idx on public.products (shop_id);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references public.shops (id) on delete restrict,
  customer_id uuid not null references auth.users (id) on delete restrict,
  status text not null default 'pending'
    check (status in ('pending', 'preparing', 'ready', 'completed', 'cancelled')),
  total_cents integer not null check (total_cents >= 0),
  -- Generated by the client once per checkout attempt and reused on retries.
  idempotency_key uuid not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (customer_id, idempotency_key)
);
create index orders_shop_id_created_at_idx on public.orders (shop_id, created_at desc);
create index orders_customer_id_created_at_idx on public.orders (customer_id, created_at desc);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders (id) on delete cascade,
  product_id uuid not null references public.products (id) on delete restrict,
  quantity integer not null check (quantity between 1 and 99),
  -- Price snapshot at order time so later price changes don't alter old orders.
  unit_price_cents integer not null check (unit_price_cents >= 0)
);
create index order_items_order_id_idx on public.order_items (order_id);

-- Append-only ledger: balance = sum(points). One entry per (order, reason)
-- so awarding points for an order can be retried safely.
create table public.loyalty_ledger (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references auth.users (id) on delete cascade,
  shop_id uuid not null references public.shops (id) on delete cascade,
  order_id uuid references public.orders (id) on delete restrict,
  points integer not null check (points <> 0),
  reason text not null check (reason in ('order', 'redemption', 'adjustment')),
  created_at timestamptz not null default now(),
  unique (order_id, reason)
);
create index loyalty_ledger_customer_shop_idx on public.loyalty_ledger (customer_id, shop_id);

create view public.loyalty_balances
with (security_invoker = true) as
  select customer_id, shop_id, sum(points)::integer as points
  from public.loyalty_ledger
  group by customer_id, shop_id;

-- ---------------------------------------------------------------------------
-- Helpers & triggers
-- ---------------------------------------------------------------------------

create function public.is_shop_staff(p_shop_id uuid, p_roles text[] default array['owner', 'barista'])
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.shop_staff
    where shop_id = p_shop_id
      and user_id = (select auth.uid())
      and role = any (p_roles)
  );
$$;

create function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, new.raw_user_meta_data ->> 'display_name');
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

create function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger orders_set_updated_at
  before update on public.orders
  for each row execute function public.set_updated_at();

-- Staff may only change an order's status, not its money or owner.
create function public.guard_order_update()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.shop_id <> old.shop_id
     or new.customer_id <> old.customer_id
     or new.total_cents <> old.total_cents
     or new.idempotency_key <> old.idempotency_key
     or new.created_at <> old.created_at then
    raise exception 'Only the order status can be changed.' using errcode = '42501';
  end if;
  return new;
end;
$$;

create trigger orders_guard_update
  before update on public.orders
  for each row execute function public.guard_order_update();

-- ---------------------------------------------------------------------------
-- place_order: the only way to create an order. Idempotent per
-- (customer, idempotency_key); prices come from the products table, never the client.
-- p_items: [{ "productId": uuid, "quantity": int }, ...]
-- ---------------------------------------------------------------------------

create function public.place_order(p_shop_id uuid, p_items jsonb, p_idempotency_key uuid)
returns public.orders
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_customer uuid := (select auth.uid());
  v_order public.orders;
  v_total integer;
  v_item_count integer;
  v_valid_count integer;
begin
  if v_customer is null then
    raise exception 'You need to sign in to place an order.' using errcode = '28000';
  end if;
  if p_idempotency_key is null then
    raise exception 'Missing order reference.' using errcode = '22023';
  end if;

  -- Replay: same customer + key returns the original order.
  select * into v_order from public.orders
  where customer_id = v_customer and idempotency_key = p_idempotency_key;
  if found then
    return v_order;
  end if;

  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Your order is empty.' using errcode = '22023';
  end if;
  if jsonb_array_length(p_items) > 50 then
    raise exception 'Too many items in one order.' using errcode = '22023';
  end if;

  v_item_count := jsonb_array_length(p_items);
  if exists (
    select 1 from jsonb_to_recordset(p_items) as i("productId" uuid, quantity integer)
    where i."productId" is null or i.quantity is null or i.quantity not between 1 and 99
  ) then
    raise exception 'Each item needs a product and a quantity between 1 and 99.' using errcode = '22023';
  end if;

  select count(*), coalesce(sum(i.quantity * p.price_cents), 0)
    into v_valid_count, v_total
  from jsonb_to_recordset(p_items) as i("productId" uuid, quantity integer)
  join public.products p on p.id = i."productId"
  where p.shop_id = p_shop_id and p.is_available;

  if v_valid_count <> v_item_count then
    raise exception 'One or more products are not available at this shop.' using errcode = '22023';
  end if;

  insert into public.orders (shop_id, customer_id, total_cents, idempotency_key)
  values (p_shop_id, v_customer, v_total, p_idempotency_key)
  on conflict (customer_id, idempotency_key) do nothing
  returning * into v_order;

  if v_order.id is null then
    -- A concurrent retry won the race; return its order.
    select * into v_order from public.orders
    where customer_id = v_customer and idempotency_key = p_idempotency_key;
    return v_order;
  end if;

  insert into public.order_items (order_id, product_id, quantity, unit_price_cents)
  select v_order.id, i."productId", i.quantity, p.price_cents
  from jsonb_to_recordset(p_items) as i("productId" uuid, quantity integer)
  join public.products p on p.id = i."productId";

  return v_order;
end;
$$;

revoke all on function public.place_order(uuid, jsonb, uuid) from public, anon;
grant execute on function public.place_order(uuid, jsonb, uuid) to authenticated;

-- ---------------------------------------------------------------------------
-- Row level security
-- ---------------------------------------------------------------------------

alter table public.profiles enable row level security;
alter table public.shops enable row level security;
alter table public.shop_staff enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.loyalty_ledger enable row level security;

-- profiles: each user reads/updates only their own.
create policy "profiles: owner can read" on public.profiles
  for select to authenticated using (id = (select auth.uid()));
create policy "profiles: owner can update" on public.profiles
  for update to authenticated using (id = (select auth.uid())) with check (id = (select auth.uid()));

-- shops & products: public menu; only shop owners edit.
create policy "shops: anyone can read" on public.shops
  for select to anon, authenticated using (true);
create policy "shops: owner can update" on public.shops
  for update to authenticated
  using (public.is_shop_staff(id, array['owner'])) with check (public.is_shop_staff(id, array['owner']));

create policy "products: anyone can read" on public.products
  for select to anon, authenticated using (true);
create policy "products: owner can insert" on public.products
  for insert to authenticated with check (public.is_shop_staff(shop_id, array['owner']));
create policy "products: owner can update" on public.products
  for update to authenticated
  using (public.is_shop_staff(shop_id, array['owner'])) with check (public.is_shop_staff(shop_id, array['owner']));
create policy "products: owner can delete" on public.products
  for delete to authenticated using (public.is_shop_staff(shop_id, array['owner']));

-- shop_staff: staff see their shop's team; owners manage it.
create policy "shop_staff: staff can read" on public.shop_staff
  for select to authenticated using (user_id = (select auth.uid()) or public.is_shop_staff(shop_id));
create policy "shop_staff: owner can insert" on public.shop_staff
  for insert to authenticated with check (public.is_shop_staff(shop_id, array['owner']));
create policy "shop_staff: owner can delete" on public.shop_staff
  for delete to authenticated using (public.is_shop_staff(shop_id, array['owner']));

-- orders: customers see their own; staff see and update their shop's.
-- No insert/delete policies: orders are created only through place_order().
create policy "orders: customer or staff can read" on public.orders
  for select to authenticated
  using (customer_id = (select auth.uid()) or public.is_shop_staff(shop_id));
create policy "orders: staff can update status" on public.orders
  for update to authenticated
  using (public.is_shop_staff(shop_id)) with check (public.is_shop_staff(shop_id));

create policy "order_items: visible with the order" on public.order_items
  for select to authenticated
  using (exists (
    select 1 from public.orders o
    where o.id = order_id
      and (o.customer_id = (select auth.uid()) or public.is_shop_staff(o.shop_id))
  ));

-- loyalty: read-only for clients; written by future security-definer functions.
create policy "loyalty_ledger: customer or staff can read" on public.loyalty_ledger
  for select to authenticated
  using (customer_id = (select auth.uid()) or public.is_shop_staff(shop_id));

