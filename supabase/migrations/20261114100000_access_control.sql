-- Sales totals for a period. Managers, owners and platform admins (logged).
create function public.shop_sales_report(p_shop_id uuid, p_from timestamptz, p_to timestamptz)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_admin boolean := public.is_platform_admin();
  v_report jsonb;
begin
  if not v_admin then
    perform public.require_shop_role(p_shop_id, array['owner', 'manager']);
  end if;
  if p_from is null or p_to is null or p_to <= p_from then
    raise exception 'Choose a valid date range.' using errcode = '22023';
  end if;
  if p_to - p_from > interval '366 days' then
    raise exception 'Reports can cover at most one year.' using errcode = '22023';
  end if;

  select jsonb_build_object(
    'orders', count(*) filter (where status <> 'cancelled'),
    'completed', count(*) filter (where status = 'completed'),
    'cancelled', count(*) filter (where status = 'cancelled'),
    'revenue_cents', coalesce(sum(total_cents) filter (where status = 'completed' and payment_status <> 'refunded'), 0),
    'refunded_cents', coalesce(sum(total_cents) filter (where payment_status = 'refunded'), 0)
  ) into v_report
  from public.orders
  where shop_id = p_shop_id and created_at >= p_from and created_at < p_to;

  if v_admin and not public.has_shop_role(p_shop_id) then
    perform public.write_audit((select auth.uid()), p_shop_id, 'admin.report.view', 'shop:' || p_shop_id,
      jsonb_build_object('from', p_from, 'to', p_to));
  end if;
  return v_report;
end;
$$;

