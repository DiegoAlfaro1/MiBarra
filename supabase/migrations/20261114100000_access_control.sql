-- Staff logins (created by the staff-invite function) get no customers row.
-- The metadata only decides that no customer profile is created; it grants nothing.
-- Staff access always requires an active shop_members row, which only invitations create.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if coalesce(new.raw_app_meta_data ->> 'account_type', new.raw_user_meta_data ->> 'account_type') = 'staff' then
    return new;
  end if;
  insert into public.customers (id, name, email, phone)
  values (
    new.id,
    new.raw_user_meta_data ->> 'display_name',
    nullif(new.email, ''),
    nullif(new.phone, '')
  );
  return new;
end;
$$;

