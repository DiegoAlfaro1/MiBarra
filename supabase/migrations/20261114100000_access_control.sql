-- MiBarra access control (issue #22).
-- Who can do what is decided here, in the database. The dashboard only hides buttons.
--
--   shop_members     (was shop_staff) links a staff login to a shop with a role
--   platform_admins  logins that can act across all shops (setup and support)
--   audit_log        append-only record of sensitive actions
--
-- Roles are looked up on every request (shop_role()), never read from the login token,
-- so setting shop_members.active = false ends access immediately.
-- Sensitive actions (refunds, late cancellations, payment settings, staff changes,
-- loyalty rules, admin actions) only run through the security-definer functions below,
-- which check the role again and write to audit_log in the same transaction.
-- See docs/access-control.md.

