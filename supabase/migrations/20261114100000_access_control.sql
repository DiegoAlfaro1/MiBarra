-- ---------------------------------------------------------------------------
-- Order status guard: direct client updates cannot cancel or reopen orders
-- ---------------------------------------------------------------------------

-- Signed-in clients may only change an order's status, and only between the working states.
-- Cancelling goes through cancel_order(), which checks who may cancel at each stage.
-- Server-side code (service role, or the security-definer functions in this file, which run
-- as their owner instead of 'authenticated') is trusted.
create or replace function public.guard_order_update()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if (select auth.uid()) is null or current_user not in ('authenticated', 'anon') then
    return new;
  end if;
  if new.shop_id <> old.shop_id
     or new.customer_id <> old.customer_id
     or new.total_cents <> old.total_cents
     or new.idempotency_key <> old.idempotency_key
     or new.created_at <> old.created_at
     or new.pickup_time is distinct from old.pickup_time
     or new.note is distinct from old.note
     or new.payment_status <> old.payment_status
     or (old.loyalty_awarded_at is not null and new.loyalty_awarded_at is distinct from old.loyalty_awarded_at) then
    raise exception 'Only the order status can be changed.' using errcode = '42501';
  end if;
  if new.status <> old.status and old.status = 'cancelled' then
    raise exception 'A cancelled order can''t be reopened.' using errcode = '42501';
  end if;
  if new.status <> old.status and new.status = 'cancelled' then
    raise exception 'Use cancel_order() to cancel an order.' using errcode = '42501';
  end if;
  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- Orders: cancel, refund, mark paid
-- ---------------------------------------------------------------------------

-- Customers cancel their own order before preparation starts; baristas can too.
-- After preparation starts only managers and owners can cancel, and it is logged.
-- Calling it again for a cancelled order returns it unchanged.
create function public.cancel_order(p_order_id uuid, p_reason text default null)
returns public.orders
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := (select auth.uid());
  v_order public.orders;
  v_role text;
begin
  if v_user is null then
    raise exception 'You need to sign in.' using errcode = '28000';
  end if;
  if p_reason is not null and char_length(p_reason) > 280 then
    raise exception 'The reason is too long.' using errcode = '22023';
  end if;

  select * into v_order from public.orders where id = p_order_id for update;
  if found and v_order.customer_id <> v_user then
    v_role := public.shop_role(v_order.shop_id);
  end if;
  if not found or (v_order.customer_id <> v_user and v_role is null) then
    raise exception 'Order not found.' using errcode = '22023';
  end if;

  if v_order.status = 'cancelled' then
    return v_order;
  end if;
  if v_order.status = 'completed' then
    raise exception 'A completed order can''t be cancelled.' using errcode = '22023';
  end if;
  if v_order.status <> 'pending' and coalesce(v_role, 'customer') not in ('owner', 'manager') then
    raise exception 'This order is already being prepared and can''t be cancelled.' using errcode = '42501';
  end if;

  update public.orders set status = 'cancelled' where id = p_order_id returning * into v_order;

  if v_role is not null then
    perform public.write_audit(
      v_user, v_order.shop_id,
      case when v_role in ('owner', 'manager') then 'order.cancel' else 'order.cancel_pending' end,
      'order:' || p_order_id,
      jsonb_build_object('reason', nullif(btrim(p_reason), '')));
  end if;
  return v_order;
end;
$$;

-- Managers and owners refund a paid order. Logged. Calling it again returns the order unchanged.
-- Money is returned through the payment provider; this records the decision.
create function public.refund_order(p_order_id uuid, p_reason text default null)
returns public.orders
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order public.orders;
begin
  if p_reason is not null and char_length(p_reason) > 280 then
    raise exception 'The reason is too long.' using errcode = '22023';
  end if;
  select * into v_order from public.orders where id = p_order_id for update;
  if not found or not public.has_shop_role(v_order.shop_id) then
    raise exception 'Order not found.' using errcode = '22023';
  end if;
  perform public.require_shop_role(v_order.shop_id, array['owner', 'manager']);

  if v_order.payment_status = 'refunded' then
    return v_order;
  end if;
  if v_order.payment_status <> 'paid' then
    raise exception 'Only paid orders can be refunded.' using errcode = '22023';
  end if;

  update public.orders set payment_status = 'refunded' where id = p_order_id returning * into v_order;
  perform public.write_audit(
    (select auth.uid()), v_order.shop_id, 'order.refund', 'order:' || p_order_id,
    jsonb_build_object('total_cents', v_order.total_cents, 'reason', nullif(btrim(p_reason), '')));
  return v_order;
end;
$$;

-- Shop staff mark an order as paid (e.g. cash at the counter). Calling it again changes nothing.
create function public.mark_order_paid(p_order_id uuid)
returns public.orders
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order public.orders;
begin
  select * into v_order from public.orders where id = p_order_id for update;
  if not found or not public.has_shop_role(v_order.shop_id) then
    raise exception 'Order not found.' using errcode = '22023';
  end if;
  if v_order.payment_status = 'paid' then
    return v_order;
  end if;
  if v_order.payment_status = 'refunded' then
    raise exception 'This order was refunded.' using errcode = '22023';
  end if;
  if v_order.status = 'cancelled' then
    raise exception 'This order was cancelled.' using errcode = '22023';
  end if;
  update public.orders set payment_status = 'paid' where id = p_order_id returning * into v_order;
  return v_order;
end;
$$;

