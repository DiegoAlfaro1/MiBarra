$$;

-- Second check and the actual change. Service role only (called by the staff-invite edge function).
-- Re-inviting an active member with the same role returns their row unchanged.
create function public.add_shop_member(p_actor uuid, p_shop_id uuid, p_user_id uuid, p_role text)
returns public.shop_members
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_member public.shop_members;
begin
  if not public.can_manage_role(public.member_role(p_shop_id, p_actor), public.user_is_platform_admin(p_actor), p_role) then
    raise exception 'You don''t have permission to invite this role at this shop.' using errcode = '42501';
  end if;
  if exists (select 1 from public.customers where id = p_user_id) then
    raise exception 'This email belongs to a customer account. Use a different email for the staff login.'
      using errcode = '22023';
  end if;

  select * into v_member from public.shop_members where shop_id = p_shop_id and user_id = p_user_id for update;
  if found and v_member.active then
    if v_member.role = p_role then
      return v_member;
    end if;
    raise exception 'This person already works at this shop.' using errcode = '22023';
  end if;

  insert into public.shop_members (shop_id, user_id, role, active, invited_by)
  values (p_shop_id, p_user_id, p_role, true, p_actor)
  on conflict (shop_id, user_id) do update
  set role = excluded.role, active = true, invited_by = excluded.invited_by
  returning * into v_member;

  perform public.write_audit(p_actor, p_shop_id, 'staff.invite', 'user:' || p_user_id,
    jsonb_build_object('role', p_role));
  return v_member;
end;
$$;

-- Removes someone from a shop (active = false), which ends their access at once. Logged.
-- Owners remove anyone except the last owner, managers remove baristas, platform admins anyone.
create function public.remove_shop_member(p_shop_id uuid, p_user_id uuid)
returns public.shop_members
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := (select auth.uid());
  v_member public.shop_members;
begin
  if v_actor is null then
    raise exception 'You need to sign in.' using errcode = '28000';
  end if;
  -- Lock the shop's team so two removals can't both remove the last owner.
  perform 1 from public.shop_members where shop_id = p_shop_id for update;
  select * into v_member from public.shop_members where shop_id = p_shop_id and user_id = p_user_id;
  if not found or not (public.has_shop_role(p_shop_id) or public.is_platform_admin()) then
    raise exception 'Staff member not found.' using errcode = '22023';
  end if;
  if not public.can_manage_role(public.shop_role(p_shop_id), public.is_platform_admin(), v_member.role) then
    raise exception 'You don''t have permission to remove this person.' using errcode = '42501';
  end if;
  if not v_member.active then
    return v_member;
  end if;
  if v_member.role = 'owner' and not exists (
    select 1 from public.shop_members
    where shop_id = p_shop_id and role = 'owner' and active and user_id <> p_user_id
  ) then
    raise exception 'A shop needs at least one owner.' using errcode = '22023';
  end if;

  update public.shop_members set active = false
  where shop_id = p_shop_id and user_id = p_user_id
  returning * into v_member;
  perform public.write_audit(v_actor, p_shop_id, 'staff.remove', 'user:' || p_user_id,
    jsonb_build_object('role', v_member.role));
  return v_member;
end;
$$;

-- Service role only: what kind of account an email already has, for the staff-invite function.
-- An account is 'staff' only if the server marked it (app metadata), or the server invited it
-- (invited_at) and it never became a customer. What a user types at sign-up never makes it staff.
create function public.account_for_email(p_email text)
returns table (user_id uuid, account_type text, confirmed boolean)
language sql
stable
security definer
set search_path = ''
as $$
  select u.id,
    case
      when u.raw_app_meta_data ->> 'account_type' = 'staff'
        or (u.invited_at is not null and not exists (select 1 from public.customers c where c.id = u.id))
      then 'staff'
      else 'customer'
    end,
    u.email_confirmed_at is not null
  from auth.users u
  where lower(u.email) = lower(btrim(p_email));
$$;

