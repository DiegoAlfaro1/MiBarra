-- ---------------------------------------------------------------------------
-- Loyalty: staff scan a customer's QR code to add a stamp or redeem a reward
-- ---------------------------------------------------------------------------

-- Idempotent per p_idempotency_key: a retried scan returns the card without changing it again.
create function public.scan_loyalty_card(
  p_shop_id uuid,
  p_qr_code text,
  p_action text,
  p_idempotency_key uuid
)
returns public.loyalty_cards
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_card public.loyalty_cards;
  v_required integer;
  v_scan public.loyalty_scans;
begin
  perform public.require_shop_role(p_shop_id, array['owner', 'manager', 'barista']);
  if p_action is null or p_action not in ('stamp', 'redeem') then
    raise exception 'Choose stamp or redeem.' using errcode = '22023';
  end if;
  if p_idempotency_key is null then
    raise exception 'Missing scan reference.' using errcode = '22023';
  end if;

  select * into v_scan from public.loyalty_scans where idempotency_key = p_idempotency_key;
  if found then
    if v_scan.shop_id <> p_shop_id then
      raise exception 'Missing scan reference.' using errcode = '22023';
    end if;
    select * into v_card from public.loyalty_cards where id = v_scan.card_id;
    return v_card;
  end if;

  select loyalty_stamps_required into v_required from public.shops where id = p_shop_id;
  if v_required is null then
    raise exception 'This shop has no loyalty program.' using errcode = '22023';
  end if;

  select * into v_card from public.loyalty_cards
  where qr_code_value = p_qr_code and shop_id = p_shop_id
  for update;
  if not found then
    raise exception 'This code isn''t a loyalty card for this shop.' using errcode = '22023';
  end if;

  insert into public.loyalty_scans (card_id, shop_id, customer_id, staff_id, action, idempotency_key)
  values (v_card.id, p_shop_id, v_card.customer_id, (select auth.uid()), p_action, p_idempotency_key)
  on conflict (idempotency_key) do nothing
  returning * into v_scan;
  if v_scan.id is null then
    -- A concurrent retry won the race.
    select * into v_card from public.loyalty_cards where id = v_card.id;
    return v_card;
  end if;

  if p_action = 'stamp' then
    update public.loyalty_cards
    set stamps = (stamps + 1) % v_required,
        rewards_available = rewards_available + (stamps + 1) / v_required
    where id = v_card.id
    returning * into v_card;
  else
    if v_card.rewards_available < 1 then
      raise exception 'No reward is available on this card yet.' using errcode = '22023';
    end if;
    update public.loyalty_cards
    set rewards_available = rewards_available - 1
    where id = v_card.id
    returning * into v_card;
  end if;
  return v_card;
end;
$$;

