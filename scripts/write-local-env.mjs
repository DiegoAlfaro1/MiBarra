// Writes the local Supabase URL and anon key into each app's .env.development.local.
// Expo only loads that file for `expo start`, so it never ends up in a production export.
// The URL uses this PC's network IP (not 127.0.0.1) so a phone on the same Wi-Fi can reach it.
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { networkInterfaces } from 'node:os';

// Skip virtual adapters (WSL, Docker, VMs); they aren't reachable from a phone.
// ponytail: picks the first real IPv4; set DEV_HOST=<ip> if it picks the wrong one.
const lanIp = Object.entries(networkInterfaces())
  .filter(([name]) => !/vEthernet|WSL|Docker|VirtualBox|VMware|Hyper-V/i.test(name))
  .flatMap(([, addrs]) => addrs ?? [])
  .find((a) => a.family === 'IPv4' && !a.internal)?.address;
const host = process.env.DEV_HOST || lanIp || '127.0.0.1';

const status = execSync('supabase status -o env', { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
const env = Object.fromEntries([...status.matchAll(/^(\w+)="(.*)"$/gm)].map(([, k, v]) => [k, v]));

if (!env.API_URL || !env.ANON_KEY) {
  console.error('Could not read API_URL / ANON_KEY from `supabase status`. Is local Supabase running?');
  process.exit(1);
}

const contents = `# Generated by \`npm run dev\` for local Supabase. Do not commit.
EXPO_PUBLIC_SUPABASE_URL=${env.API_URL.replace('127.0.0.1', host)}
EXPO_PUBLIC_SUPABASE_ANON_KEY=${env.ANON_KEY}
`;
for (const app of ['mobile', 'dashboard']) {
  writeFileSync(`apps/${app}/.env.development.local`, contents);
}
console.log(`Wrote apps/*/.env.development.local (Supabase at ${host}). Run \`npm run mobile\` in another terminal for the app.`);
