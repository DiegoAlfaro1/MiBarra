alter table public.shop_members rename constraint shop_staff_pkey to shop_members_pkey;
alter table public.shop_members rename constraint shop_staff_shop_id_fkey to shop_members_shop_id_fkey;
alter table public.shop_members rename constraint shop_staff_user_id_fkey to shop_members_user_id_fkey;
alter index public.shop_staff_user_id_idx rename to shop_members_user_id_idx;

alter table public.shop_members drop constraint shop_staff_role_check;
alter table public.shop_members
  add constraint shop_members_role_check check (role in ('owner', 'manager', 'barista')),
  -- Removing someone sets active = false so the row (and who invited them) is kept.
  add column active boolean not null default true,
  add column invited_by uuid references auth.users (id) on delete set null;

