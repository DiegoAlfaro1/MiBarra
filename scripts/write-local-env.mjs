// Writes the local Supabase URL and anon key into each app's .env.development.local.
// Expo only loads that file for `expo start`, so it never ends up in a production export.
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const status = execSync('supabase status -o env', { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
const env = Object.fromEntries([...status.matchAll(/^(\w+)="(.*)"$/gm)].map(([, k, v]) => [k, v]));

if (!env.API_URL || !env.ANON_KEY) {
  console.error('Could not read API_URL / ANON_KEY from `supabase status`. Is local Supabase running?');
  process.exit(1);
}

const contents = `# Generated by \`npm run dev\` for local Supabase. Do not commit.
EXPO_PUBLIC_SUPABASE_URL=${env.API_URL}
EXPO_PUBLIC_SUPABASE_ANON_KEY=${env.ANON_KEY}
`;
for (const app of ['mobile', 'dashboard']) {
  writeFileSync(`apps/${app}/.env.development.local`, contents);
}
console.log('Wrote apps/mobile and apps/dashboard .env.development.local');
