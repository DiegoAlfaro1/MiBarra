-- Who may invite or remove whom: owners and platform admins manage everyone, managers only baristas.
create function public.can_manage_role(p_actor_role text, p_actor_is_admin boolean, p_target_role text)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select p_target_role in ('owner', 'manager', 'barista') and (
    coalesce(p_actor_is_admin, false)
    or p_actor_role = 'owner'
    or (p_actor_role = 'manager' and p_target_role = 'barista')
  );
$$;

-- Writes one audit entry. Only callable from other database functions.
create function public.write_audit(
  p_user_id uuid,
  p_shop_id uuid,
  p_action text,
  p_target text,
  p_details jsonb default '{}'::jsonb
)
returns void
language sql
security definer
set search_path = ''
as $$
  insert into public.audit_log (user_id, shop_id, action, target, details)
  values (p_user_id, p_shop_id, p_action, p_target, coalesce(p_details, '{}'::jsonb));
$$;

-- Raises unless the signed-in user has one of p_roles at the shop. Returns their role.
create function public.require_shop_role(p_shop_id uuid, p_roles text[])
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_role text;
begin
  if (select auth.uid()) is null then
    raise exception 'You need to sign in.' using errcode = '28000';
  end if;
  v_role := public.shop_role(p_shop_id);
  if v_role is null or not (v_role = any (p_roles)) then
    raise exception 'You don''t have permission to do that at this shop.' using errcode = '42501';
  end if;
  return v_role;
end;
$$;

