-- ---------------------------------------------------------------------------
-- audit_log: append-only. No foreign keys, so entries survive when a user or shop is deleted.
-- ---------------------------------------------------------------------------

create table public.audit_log (
  id bigint generated always as identity primary key,
  -- The login that performed the action (null for server jobs without a user).
  user_id uuid,
  shop_id uuid,
  action text not null check (char_length(action) between 1 and 80),
  -- What was acted on, e.g. 'order:<id>' or 'user:<id>'.
  target text check (target is null or char_length(target) <= 200),
  details jsonb not null default '{}'::jsonb check (jsonb_typeof(details) = 'object'),
  time timestamptz not null default now()
);
create index audit_log_shop_time_idx on public.audit_log (shop_id, time desc);
create index audit_log_user_time_idx on public.audit_log (user_id, time desc);

create function public.audit_log_is_append_only()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  raise exception 'The audit log cannot be changed.' using errcode = '42501';
end;
$$;

create trigger audit_log_append_only
  before update or delete on public.audit_log
  for each row execute function public.audit_log_is_append_only();

revoke all on public.audit_log from anon, authenticated;
grant select on public.audit_log to authenticated;

