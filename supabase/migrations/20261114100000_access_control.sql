-- ---------------------------------------------------------------------------
-- Platform admin writes to the menu are logged (every admin action is recorded)
-- ---------------------------------------------------------------------------

create function public.audit_platform_admin_menu_write()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_row record;
  v_shop uuid;
begin
  if not public.is_platform_admin() then
    return null;
  end if;
  if tg_op = 'DELETE' then
    v_row := old;
  else
    v_row := new;
  end if;
  if tg_table_name = 'item_options' then
    select shop_id into v_shop from public.menu_items where id = v_row.item_id;
  else
    v_shop := v_row.shop_id;
  end if;
  perform public.write_audit(
    (select auth.uid()), v_shop, 'admin.' || tg_table_name || '.' || lower(tg_op), tg_table_name || ':' || v_row.id);
  return null;
end;
$$;

create trigger menu_categories_audit_admin
  after insert or update or delete on public.menu_categories
  for each row execute function public.audit_platform_admin_menu_write();
create trigger menu_items_audit_admin
  after insert or update or delete on public.menu_items
  for each row execute function public.audit_platform_admin_menu_write();
create trigger item_options_audit_admin
  after insert or update or delete on public.item_options
  for each row execute function public.audit_platform_admin_menu_write();

